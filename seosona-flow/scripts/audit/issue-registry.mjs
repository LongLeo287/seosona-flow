#!/usr/bin/env node
// P1.T7 — Establish issue registry. Emits issues.json + issue-registry.md.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { repoRoot, stableJson } from './lib/repo.mjs';
import { PHASE_OWNER, FACTS, AUD, SEC, UNKNOWNS } from './lib/issues-data.mjs';

const JSON_REL = 'seosona-flow/artifacts/audit/issues.json';
const MD_REL = 'docs/audits/issue-registry.md';

function buildIssues() {
  const findings = [...AUD, ...SEC].map((i) => ({
    id: i.id,
    kind: 'finding',
    severity: i.severity,
    family: i.family,
    evidence: i.evidence,
    targetPhase: i.phase,
    owner: PHASE_OWNER[i.phase],
    relatedFindings: i.relatedFindings || [],
    closureCriteria: `Closed when Phase ${i.phase} tasks that reference ${i.id} pass their verification commands with independent acceptance.`,
    status: 'open',
  })).sort((a, b) => a.id.localeCompare(b.id));

  return {
    schema: 'seosona.audit.issues.v1',
    counts: {
      facts: FACTS.length,
      findings: findings.length,
      aud: AUD.length,
      sec: SEC.length,
      unknowns: UNKNOWNS.length,
    },
    facts: FACTS,
    findings,
    unknowns: UNKNOWNS.map((u) => ({ ...u, owner: PHASE_OWNER[u.phase] })),
  };
}

function renderMd(data) {
  const lines = [];
  lines.push('# SEOSONA Flow Issue Registry');
  lines.push('');
  lines.push('> Generated by `scripts/audit/issue-registry.mjs` from `scripts/audit/lib/issues-data.mjs`.');
  lines.push('> Regenerate with `node scripts/audit/issue-registry.mjs`; verify with `--check`.');
  lines.push('');
  lines.push('This registry separates **facts** (reproduced by Phase 1 artifacts), **findings** (AUD/SEC issues each roadmap task must reference), and **unknowns** (sealed-report follow-ups with unproven impact).');
  lines.push('');
  lines.push('## Facts');
  lines.push('');
  lines.push('| ID | Statement | Evidence |');
  lines.push('|---|---|---|');
  for (const f of data.facts) lines.push(`| ${f.id} | ${f.statement} | \`${f.evidence}\` |`);
  lines.push('');
  lines.push('## Findings');
  lines.push('');
  lines.push('| ID | Severity | Family | Phase | Owner | Evidence |');
  lines.push('|---|---|---|---:|---|---|');
  for (const i of data.findings) {
    lines.push(`| ${i.id} | ${i.severity} | ${i.family} | ${i.targetPhase} | ${i.owner} | ${i.evidence} |`);
  }
  lines.push('');
  lines.push('## Unknowns');
  lines.push('');
  lines.push('| ID | Related finding | Open question | Phase |');
  lines.push('|---|---|---|---:|');
  for (const u of data.unknowns) lines.push(`| ${u.id} | ${u.relatedFinding} | ${u.question} | ${u.phase} |`);
  lines.push('');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const root = repoRoot();
  const data = buildIssues();
  const json = stableJson(data);
  const md = renderMd(data);
  const jsonPath = join(root, JSON_REL);
  const mdPath = join(root, MD_REL);

  if (check) {
    const jsonOk = existsSync(jsonPath) && readFileSync(jsonPath, 'utf8') === json;
    const mdOk = existsSync(mdPath) && readFileSync(mdPath, 'utf8') === md;
    if (!jsonOk || !mdOk) {
      console.error(`[issues] DRIFT: json=${jsonOk ? 'ok' : 'stale'} md=${mdOk ? 'ok' : 'stale'}`);
      process.exit(1);
    }
    console.log(`[issues] OK facts=${data.counts.facts} findings=${data.counts.findings} unknowns=${data.counts.unknowns}`);
    return;
  }

  mkdirSync(dirname(jsonPath), { recursive: true });
  mkdirSync(dirname(mdPath), { recursive: true });
  writeFileSync(jsonPath, json);
  writeFileSync(mdPath, md);
  console.log(`[issues] wrote ${JSON_REL} and ${MD_REL}`);
  console.log(`  facts=${data.counts.facts} findings=${data.counts.findings} (AUD=${data.counts.aud} SEC=${data.counts.sec}) unknowns=${data.counts.unknowns}`);
}

main();

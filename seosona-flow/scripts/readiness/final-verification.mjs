#!/usr/bin/env node
// SEOSONA Flow — Release-candidate final verification (Phase 10 / P10.T7, AUD-032).
// Aggregates the evidence produced across all phases into a single verdict:
// scope, tests, security, privacy, a11y, performance, SBOM, package, and
// governance. Verdict is ACCEPTED only when every required evidence artifact
// exists and every gate is present. Deterministic report + `--check`, plus a
// human-readable audit doc.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { repoRoot, stableJson } from '../audit/lib/repo.mjs';
import { VERIFY_TIERS } from '../quality/lib/tiers.mjs';

const ROOT = repoRoot();
const OUT = join(ROOT, 'seosona-flow/artifacts/readiness/phase-10/final-verification.json');
const DOC = join(ROOT, 'docs/audits/release-candidate-audit.md');

// Required evidence artifacts, keyed by dimension.
const EVIDENCE = {
  scope: 'seosona-flow/artifacts/audit/phase-01/repository-inventory.json',
  privacy: 'seosona-flow/artifacts/privacy/phase-07/network-inventory.json',
  providers: 'seosona-flow/artifacts/providers/phase-06/provider-matrix.json',
  a11y: 'seosona-flow/artifacts/ux/phase-08/a11y-report.json',
  performance: 'seosona-flow/artifacts/ux/phase-08/page-profile.json',
  sbom: 'seosona-flow/artifacts/release/phase-09/sbom.json',
  package: 'seosona-flow/artifacts/release/phase-09/package-manifest.json',
  drills: 'seosona-flow/artifacts/readiness/phase-10/drills.json',
};

function build() {
  const dimensions = Object.entries(EVIDENCE).map(([dim, rel]) => ({ dimension: dim, evidence: rel, present: existsSync(join(ROOT, rel)) }));
  const missing = dimensions.filter((d) => !d.present).map((d) => d.dimension);
  const gates = VERIFY_TIERS.map((t) => t.id);
  // Pull a couple of key facts for the receipt.
  let reproHash = null, drills = null, sbomComponents = null;
  try { reproHash = JSON.parse(readFileSync(join(ROOT, EVIDENCE.package), 'utf8')).reproHash; } catch { /* n/a */ }
  try { const d = JSON.parse(readFileSync(join(ROOT, EVIDENCE.drills), 'utf8')); drills = { total: d.total, unhandled: d.unhandled }; } catch { /* n/a */ }
  try { const s = JSON.parse(readFileSync(join(ROOT, EVIDENCE.sbom), 'utf8')); sbomComponents = s.components.length; } catch { /* n/a */ }
  const verdict = missing.length === 0 && (!drills || drills.unhandled === 0) ? 'ACCEPTED' : 'BLOCKED';
  return {
    schema: 'seosona.readiness.final.v1',
    verdict,
    gateCount: gates.length,
    gates,
    dimensions,
    missing,
    facts: { reproHash, drills, sbomComponents },
  };
}

function doc(report) {
  const lines = ['# Release Candidate Audit', '', `**Verdict: ${report.verdict}**`, '',
    `- Verification gates: ${report.gateCount} (${report.gates.join(', ')})`,
    `- Evidence dimensions: ${report.dimensions.length}, missing: ${report.missing.length ? report.missing.join(', ') : 'none'}`,
    `- Package reproducibility hash: \`${report.facts.reproHash ? report.facts.reproHash.slice(0, 16) + '…' : 'n/a'}\``,
    `- SBOM components: ${report.facts.sbomComponents ?? 'n/a'}`,
    `- Reliability drills: ${report.facts.drills ? report.facts.drills.total + ' (' + report.facts.drills.unhandled + ' unhandled)' : 'n/a'}`,
    '', '## Evidence', ''];
  for (const d of report.dimensions) lines.push(`- ${d.present ? '✓' : '✗'} **${d.dimension}** — \`${d.evidence}\``);
  lines.push('', '> Generated by `scripts/readiness/final-verification.mjs`. Do not edit by hand.', '');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const report = build();
  const json = stableJson(report);
  const md = doc(report);
  if (report.verdict !== 'ACCEPTED') { console.error('[final] verdict BLOCKED — missing: ' + report.missing.join(', ')); process.exit(1); }
  if (check) {
    let curJson = null, curMd = null;
    try { curJson = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    try { curMd = readFileSync(DOC, 'utf8'); } catch { /* missing */ }
    if (curJson !== json || curMd !== md) { console.error('[final] drift — run `node scripts/readiness/final-verification.mjs`'); process.exit(1); }
    console.log(`[final] OK — verdict ${report.verdict}, ${report.gateCount} gates, ${report.dimensions.length} evidence dimensions.`);
    return;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  mkdirSync(dirname(DOC), { recursive: true });
  writeFileSync(OUT, json);
  writeFileSync(DOC, md);
  console.log(`[final] wrote final verification: ${report.verdict}.`);
}

import { fileURLToPath } from 'node:url';
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
export { build };
